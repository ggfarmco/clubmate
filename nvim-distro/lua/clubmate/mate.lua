function M.lualine(c)
  local function mode(color)
    return {
      a = { fg = c.on_fill, bg = color, gui = "bold" },
      b = { fg = c.fg, bg = c.raised },
      c = { fg = c.muted, bg = c.cursor_line },
    }
  end
  return {
    normal = mode(c.accent),
    insert = mode(c.mode_insert),
    visual = mode(c.mode_visual),
    command = mode(c.mode_command),
    replace = mode(c.mode_replace),
    terminal = mode(c.mode_terminal),
    inactive = {
      a = { fg = c.muted, bg = c.cursor_line },
      b = { fg = c.muted, bg = c.cursor_line },
      c = { fg = c.muted, bg = c.cursor_line },
    },
  }
end

